"""Porcine Spinal Cord ultrasound segmentation dataset preprocessing.

Dataset: B-mode ultrasound images of porcine spinal cord before/after
         contusion injury with semantic segmentation masks.
Paper:   https://doi.org/10.1038/s41598-025-05619-z
Source:  https://github.com/avishakumar21/ultrasound-spinal-cord-dataset

Data format (already extracted):
    {split}_images/{name}.png   690x275 RGB ultrasound frames
    {split}_masks/{name}.png    690x275 RGB VOC-palette semantic masks
    splits: train, val, test

Masks use a PASCAL-VOC-style colour palette (10 classes including background).
This script decodes the RGB masks to label indices, then converts each semantic
class into per-instance masks via connected-component labelling.

Categories (label id -> anatomy):
    0  background
    1  dura
    2  pia
    3  csf
    4  spinal_cord
    5  dorsal_space
    6  hematoma
    7  ventral_space
    8  dura_ventral_complex
    9  dura_pia_complex

Output: SAM2-compatible format (SA-1B style by default)
"""

import argparse
import logging
import sys
from pathlib import Path
from typing import Dict, List, Tuple

import cv2
import numpy as np

project_root = Path(__file__).resolve().parents[2]
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from ..utils.sam2_annotator import SAM2VideoAnnotator

DATASET_NAME = "PorcineSpinalCord"

CATEGORIES = [
    {"supercategory": "anatomy", "id": 1, "name": "dura"},
    {"supercategory": "anatomy", "id": 2, "name": "pia"},
    {"supercategory": "anatomy", "id": 3, "name": "csf"},
    {"supercategory": "anatomy", "id": 4, "name": "spinal_cord"},
    {"supercategory": "anatomy", "id": 5, "name": "dorsal_space"},
    {"supercategory": "pathology", "id": 6, "name": "hematoma"},
    {"supercategory": "anatomy", "id": 7, "name": "ventral_space"},
    {"supercategory": "anatomy", "id": 8, "name": "dura_ventral_complex"},
    {"supercategory": "anatomy", "id": 9, "name": "dura_pia_complex"},
]

# VOC-style colour palette: label index -> (R, G, B).
# Generated by the standard bit-interleaving scheme used by PASCAL VOC / CVAT.
_VOC_PALETTE = np.array(
    [
        [0, 0, 0],        # 0  background
        [128, 0, 0],      # 1  dura
        [0, 128, 0],      # 2  pia
        [128, 128, 0],    # 3  csf
        [0, 0, 128],      # 4  spinal_cord
        [128, 0, 128],    # 5  dorsal_space
        [0, 128, 128],    # 6  hematoma
        [128, 128, 128],  # 7  ventral_space
        [64, 0, 0],       # 8  dura_ventral_complex
        [192, 0, 0],      # 9  dura_pia_complex
    ],
    dtype=np.uint8,
)

# Pre-compute a fast lookup: pack each palette RGB into a single uint32 key.
_PALETTE_KEYS = (
    _VOC_PALETTE[:, 0].astype(np.uint32) * 65536
    + _VOC_PALETTE[:, 1].astype(np.uint32) * 256
    + _VOC_PALETTE[:, 2].astype(np.uint32)
)


def parse_args():
    parser = argparse.ArgumentParser(description=f"Convert {DATASET_NAME} to SAM2 format")
    parser.add_argument(
        "--path",
        type=str,
        default="/mnt/data/Dataset/UltraSound/Porcine-Spinal-Cord/Segmentation",
        help="Path to extracted dataset root",
    )
    parser.add_argument(
        "--save-dir",
        type=str,
        default=f"/mnt/data/Dataset/SaUS/{DATASET_NAME}",
        help="Output directory",
    )
    parser.add_argument("--format", type=str, choices=["sa-v", "sa-1b"], default="sa-1b")
    parser.add_argument(
        "--split",
        type=str,
        choices=["train", "val", "test", "all"],
        default="all",
        help="Which split to process",
    )
    parser.add_argument("--save-viz", action="store_true")
    parser.add_argument("--max-images", type=int, default=None)
    parser.add_argument("--zip", action="store_true")
    parser.add_argument("--delete", action="store_true")
    return parser.parse_args()


def rgb_mask_to_labels(mask_rgb: np.ndarray) -> np.ndarray:
    """Decode a VOC-palette RGB mask to a single-channel label map."""
    key = (
        mask_rgb[:, :, 0].astype(np.uint32) * 65536
        + mask_rgb[:, :, 1].astype(np.uint32) * 256
        + mask_rgb[:, :, 2].astype(np.uint32)
    )
    labels = np.zeros(key.shape, dtype=np.uint8)
    for idx, pk in enumerate(_PALETTE_KEYS):
        labels[key == pk] = idx
    return labels


def semantic_to_instance_mask(
    label_map: np.ndarray,
) -> Tuple[np.ndarray, Dict[int, int]]:
    """Convert a semantic label map to an instance mask.

    Each disconnected region of every semantic class becomes its own instance.
    Returns (instance_mask, instance_to_category) where instance_to_category
    maps each instance ID to its original semantic label (= category ID).
    """
    instance_mask = np.zeros(label_map.shape, dtype=np.uint16)
    instance_to_category: Dict[int, int] = {}
    next_id = 1

    for cat_id in sorted(int(v) for v in np.unique(label_map) if v != 0):
        n_comp, labeled = cv2.connectedComponents((label_map == cat_id).astype(np.uint8))
        for comp in range(1, n_comp):
            instance_mask[labeled == comp] = next_id
            instance_to_category[next_id] = cat_id
            next_id += 1

    return instance_mask, instance_to_category


def collect_samples(data_dir: Path, split: str = "all") -> List[Dict]:
    """Collect image-mask pairs from the split folders."""
    samples: List[Dict] = []
    splits = ["train", "val", "test"] if split == "all" else [split]

    for split_name in splits:
        img_dir = data_dir / f"{split_name}_images"
        mask_dir = data_dir / f"{split_name}_masks"
        if not img_dir.exists() or not mask_dir.exists():
            continue

        for img_file in sorted(img_dir.glob("*.png")):
            mask_file = mask_dir / img_file.name
            if mask_file.exists():
                samples.append(
                    {
                        "image_path": img_file,
                        "mask_path": mask_file,
                        "image_id": img_file.stem,
                        "split": split_name,
                    }
                )

    return samples


def main():
    args = parse_args()

    logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
    logger = logging.getLogger(__name__)

    save_path = Path(args.save_dir)
    data_path = Path(args.path)

    if not data_path.exists():
        logger.error(f"Dataset not found: {data_path}")
        return

    annotator = SAM2VideoAnnotator(
        out_dir=save_path,
        dataset_name=DATASET_NAME,
        categories=CATEGORIES,
        save_visualization=args.save_viz,
        video_environment="ultrasound",
        video_split="train",
    )

    logger.info(f"Output format: {args.format}, split: {args.split}")

    samples = collect_samples(data_path, args.split)
    logger.info(f"Found {len(samples)} samples")

    if args.max_images:
        samples = samples[: args.max_images]

    processed = 0
    for idx, sample in enumerate(samples):
        image = cv2.imread(str(sample["image_path"]))
        if image is None:
            continue
        image_rgb = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

        mask_bgr = cv2.imread(str(sample["mask_path"]))
        if mask_bgr is None:
            continue
        mask_rgb = cv2.cvtColor(mask_bgr, cv2.COLOR_BGR2RGB)

        label_map = rgb_mask_to_labels(mask_rgb)

        if not np.any(label_map > 0):
            continue

        instance_mask, instance_to_category = semantic_to_instance_mask(label_map)

        split_name = sample.get("split", "unknown")
        image_name = f"{split_name}_{sample['image_id']}"
        annotator.add_2d(
            image_rgb,
            instance_mask,
            video_name=image_name,
            format=args.format,
            instance_to_category=instance_to_category,
            metadata={
                "image_id": sample["image_id"],
                "split": split_name,
                "dataset": DATASET_NAME,
            },
        )
        processed += 1

        if (idx + 1) % 200 == 0:
            logger.info(f"Processed {idx + 1}/{len(samples)}")

    logger.info(f"Total processed: {processed}")

    stats = annotator.finalize()
    logger.info(f"Dataset stats: {stats}")

    if args.zip:
        import shutil

        shutil.make_archive(str(save_path), "zip", save_path)
        if args.delete:
            shutil.rmtree(save_path)

    logger.info("Done!")


if __name__ == "__main__":
    main()
